CREATE TABLE IF NOT EXISTS CHARACTERS (
    CHARACTER_ID INTEGER PRIMARY KEY,
    NAME TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS ALIAS(
	CHARACTER_ID INTEGER NOT NULL,
    ALIAS TEXT NOT NULL,
    PRIMARY KEY (CHARACTER_ID, ALIAS),
    FOREIGN KEY (CHARACTER_ID)
        REFERENCES CHARACTERS (CHARACTER_ID)
            ON DELETE CASCADE
            ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS PINGS (
    CHARACTER_ID INTEGER NOT NULL,
    USER TEXT NOT NULL,
    PRIMARY KEY (CHARACTER_ID, USER),
    FOREIGN KEY (CHARACTER_ID)
        REFERENCES CHARACTERS (CHARACTER_ID)
            ON DELETE CASCADE
            ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS GACHA_CURRENCY (
    GACHA_CURRENCY_ID INTEGER PRIMARY KEY,
    NAME TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS GACHA_CURRENCY_WALLET (
    GACHA_CURRENCY_ID INTEGER NOT NULL,
    USER TEXT NOT NULL,
    AMOUNT INTEGER NOT NULL,
    PRIMARY KEY (GACHA_CURRENCY_ID, USER),
    FOREIGN KEY (GACHA_CURRENCY_ID)
        REFERENCES GACHA_CURRENCY (GACHA_CURRENCY_ID)
            ON DELETE CASCADE
            ON UPDATE CASCADE
);

-- The live database ran without PRAGMA foreign_keys, so deleting a character or currency left its pings or wallets
-- behind; the migration runner's foreign_key_check, run after this script, would refuse them. A new database has none.
DELETE FROM PINGS WHERE CHARACTER_ID NOT IN (SELECT CHARACTER_ID FROM CHARACTERS);
DELETE FROM GACHA_CURRENCY_WALLET WHERE GACHA_CURRENCY_ID NOT IN (SELECT GACHA_CURRENCY_ID FROM GACHA_CURRENCY);
