-- Character and currency names are unique regardless of case.
-- SQLite can't add a constraint to an existing table, so both tables are rebuilt; their IDs are kept,
-- so the pings, aliases and wallets referencing them stay valid. Fails on existing duplicates, e.g. Lucina and lucina.

CREATE TABLE NEW_CHARACTERS (
    CHARACTER_ID INTEGER PRIMARY KEY,
    NAME TEXT NOT NULL UNIQUE COLLATE NOCASE
);
INSERT INTO NEW_CHARACTERS (CHARACTER_ID, NAME) SELECT CHARACTER_ID, NAME FROM CHARACTERS;
DROP TABLE CHARACTERS;
ALTER TABLE NEW_CHARACTERS RENAME TO CHARACTERS;

CREATE TABLE NEW_GACHA_CURRENCY (
    GACHA_CURRENCY_ID INTEGER PRIMARY KEY,
    NAME TEXT NOT NULL UNIQUE COLLATE NOCASE
);
INSERT INTO NEW_GACHA_CURRENCY (GACHA_CURRENCY_ID, NAME) SELECT GACHA_CURRENCY_ID, NAME FROM GACHA_CURRENCY;
DROP TABLE GACHA_CURRENCY;
ALTER TABLE NEW_GACHA_CURRENCY RENAME TO GACHA_CURRENCY;
